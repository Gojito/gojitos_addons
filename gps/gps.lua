-- Saved spots, categorized by zone: zone_id -> { name -> { x, z } }. A name is
-- only unique within its zone, so the same name (e.g. "ah") can exist in several
-- zones. Stored globally (a spawn point is the same for every character) in
-- config\addons\gps\saved_gps.lua.
local saved = {};
local saved_path = store_dir .. 'saved_gps.lua';

local function zone_name(id)
    if (id == nil) then return '?'; end
    local ok, n = pcall(function()
        return AshitaCore:GetResourceManager():GetString('zones.names', id);
    end);
    if (ok and n ~= nil and n ~= '') then return n; end
    return 'zone ' .. tostring(id);
end

-- Write the nested table back out, sorted by zone then name, with a readable
-- "-- <zone name>" comment above each zone bucket (the keys are bare zone ids).
local function save_saved()
    local f = io.open(saved_path, 'w');
    if (f == nil) then
        msg('could not write ' .. saved_path);
        return;
    end
    local zids = {};
    for zid in pairs(saved) do zids[#zids + 1] = zid; end
    table.sort(zids, function(a, b) return tostring(a) < tostring(b); end);

    f:write('return {\n');
    for _, zid in ipairs(zids) do
        local bucket = saved[zid];
        local names = {};
        for n in pairs(bucket) do names[#names + 1] = n; end
        if (#names > 0) then
            table.sort(names);
            local key = (type(zid) == 'number') and tostring(zid) or ('%q'):format(tostring(zid));
            f:write(('  -- %s\n'):format(zone_name(zid)));
            f:write(('  [%s] = {\n'):format(key));
            for _, n in ipairs(names) do
                local c = bucket[n];
                if (c.y ~= nil) then
                    f:write(('    [%q] = { x = %s, y = %s, z = %s },\n'):format(n, tostring(c.x), tostring(c.y), tostring(c.z)));
                else
                    f:write(('    [%q] = { x = %s, z = %s },\n'):format(n, tostring(c.x), tostring(c.z)));
                end
            end
            f:write('  },\n');
        end
    end
    f:write('}\n');
    f:close();
end

local function load_saved()
    local fn = loadfile(saved_path);
    if (not fn) then return; end
    local ok, r = pcall(fn);
    if (not ok or type(r) ~= 'table') then return; end

    -- Accept both the legacy flat format (name -> { x, z, zone }) and the new
    -- nested format (zone_id -> { name -> { x, z } }); migrate the former.
    local out = {};
    local migrated = false;
    for k, v in pairs(r) do
        if (type(v) == 'table' and type(v.x) == 'number' and type(v.z) == 'number') then
            -- legacy entry: k is the spot name, v carries its own zone
            local zid = v.zone or 0;
            out[zid] = out[zid] or {};
            out[zid][k] = { x = v.x, y = v.y, z = v.z };
            migrated = true;
        elseif (type(v) == 'table') then
            -- already a zone bucket: k is the zone id
            local zid = tonumber(k) or k;
            out[zid] = out[zid] or {};
            for name, c in pairs(v) do
                if (type(c) == 'table' and c.x ~= nil and c.z ~= nil) then
                    out[zid][name] = { x = c.x, y = c.y, z = c.z };
                end
            end
        end
    end
    saved = out;
    if (migrated) then save_saved(); end  -- rewrite legacy file in the new shape
end

-- Probe for whichever rotation getter this build exposes.
local function get_heading(em, idx)
    if (rot_method ~= nil) then
        local ok, v = pcall(function() return em[rot_method](em, idx); end);
        if (ok and type(v) == 'number') then return v; end
    end
    for _, name in ipairs({ 'GetLocalRotation', 'GetRotation', 'GetHeading', 'GetFacing' }) do
        local ok, v = pcall(function() return em[name](em, idx); end);
        if (ok and type(v) == 'number') then rot_method = name; return v; end
    end
    return nil;
end

-- Returns: x, y(height), z, heading  (any may be nil if unavailable)
local function get_pos()
    local mm = AshitaCore:GetMemoryManager();
    if (mm == nil) then return nil; end
    local party, em = mm:GetParty(), mm:GetEntity();
    if (party == nil or em == nil) then return nil; end

    local idx = party:GetMemberTargetIndex(0); -- slot 0 = self
    if (idx == nil or idx == 0) then return nil; end

    local ok, x, zh, yv = pcall(function()
        return em:GetLocalPositionX(idx),
               em:GetLocalPositionY(idx),  -- world Z (axis quirk)
               em:GetLocalPositionZ(idx);  -- world Y / height (axis quirk)
    end);
    if (not ok or x == nil) then return nil; end

    return x, yv, zh, get_heading(em, idx);
end

local function cur_zone()
    local mm = AshitaCore:GetMemoryManager();
    if (mm == nil) then return nil; end
    local p = mm:GetParty();
    if (p == nil) then return nil; end
    local ok, z = pcall(function() return p:GetMemberZone(0); end);
    return (ok and z) or nil;
end

-- Built-in location database, generated from the CatsEyeXI server npc_list (see
-- tools/gen_pois.py). Read-only; never written back to saved_gps.lua. Files are
-- named by zone (data/<Zone>.lua); data/index.lua maps zone id -> filename stem so
-- we can resolve the runtime numeric zone. Loaded lazily, one zone at a time.
local data_dir      = addon.path .. 'data/';
local builtin       = {};    -- zone_id -> list of { n, key, x, y, z, k }  (cached)
local builtin_index = nil;   -- zone_id -> filename stem (loaded once)

local function load_index()
    if (builtin_index ~= nil) then return; end
    builtin_index = {};
    local fn = loadfile(data_dir .. 'index.lua');
    if (not fn) then return; end
    local ok, r = pcall(fn);
    if (ok and type(r) == 'table') then builtin_index = r; end
end

local function load_builtin(zid)
    if (zid == nil) then return {}; end
    if (builtin[zid] ~= nil) then return builtin[zid]; end
    load_index();
    local list = {};
    local stem = builtin_index[zid];
    if (stem ~= nil) then
        local fn = loadfile(data_dir .. stem .. '.lua');
        if (fn) then
            local ok, r = pcall(fn);
            if (ok and type(r) == 'table') then
                for _, e in ipairs(r) do
                    if (type(e) == 'table' and e.n and e.x and e.z) then
                        list[#list + 1] = { n = e.n, key = tostring(e.n):lower(),
                                            x = e.x, y = e.y, z = e.z, k = e.k };
                    end
                end
            end
        end
    end
    builtin[zid] = list;
    return list;
end

-- Strip apostrophes for matching so a name like "Gu'Nhi Noondozer" can be typed with
-- OR without the apostrophe (and we don't depend on how the chat tokenizer handles a
-- "'"). Names still DISPLAY with the apostrophe; only matching ignores it.
local function norm(s)
    return (tostring(s):gsub("['`]", ""));
end

-- Waypoints from /gps waypoint, newest first, capped. 'armed' = auto-route once on zone-in.
local inbox = {};
local INBOX_CAP = 15;

-- Resolve a name to a spot. Order: user-saved (current zone) -> built-in (current
-- zone) -> user-saved (any zone). When several built-in entries share a name (e.g.
-- "Gate Guard"), pick the one nearest the player. Returns spot { x, y, z }, zone id,
-- and source ('saved'|'builtin'). Names are matched lowercased, apostrophe-insensitive.
local function find_spot(name)
    if (name == nil or name == '') then return nil; end
    local cz = cur_zone();
    if (cz ~= nil and saved[cz] and saved[cz][name]) then
        return saved[cz][name], cz, 'saved';
    end
    if (cz ~= nil) then
        local nname = norm(name);
        local px, _, pz = get_pos();
        local best, bestd;
        for _, e in ipairs(load_builtin(cz)) do
            if (norm(e.key) == nname) then
                if (px == nil) then
                    return { x = e.x, y = e.y, z = e.z }, cz, 'builtin';
                end
                local dx, dz = px - e.x, pz - e.z;
                local d = dx * dx + dz * dz;
                if (bestd == nil or d < bestd) then bestd = d; best = e; end
            end
        end
        if (best ~= nil) then
            return { x = best.x, y = best.y, z = best.z }, cz, 'builtin';
        end
    end
    for zid, bucket in pairs(saved) do
        if (bucket[name]) then return bucket[name], zid, 'saved'; end
    end
    return nil;
end

-- Join args[from..] into a single lowercased, single-spaced name. NPC display names
-- have spaces ("Gate Guard"), so commands that take a name accept multiple words.
local function join_name(args, from)
    if (#args < from) then return nil; end
    local t = {};
    for i = from, #args do t[#t + 1] = args[i]; end
    local s = table.concat(t, ' '):lower():gsub('%s+', ' '):gsub('^%s+', ''):gsub('%s+$', '');
    return (s ~= '') and s or nil;
end

-- Current-zone entries (saved + built-in) whose lowercased name CONTAINS q
-- (apostrophe-insensitive). Returns { n=display, key=lowername, x, y, z, src }.
-- Shared by /gps find and by /gps go's partial-name matching.
local function search_zone(q)
    local out = {};
    local cz = cur_zone();
    if (cz == nil) then return out; end
    local nq = norm(q);
    if (saved[cz]) then
        for n, c in pairs(saved[cz]) do
            if (norm(n):find(nq, 1, true)) then
                out[#out + 1] = { n = n, key = n, x = c.x, y = c.y, z = c.z, src = 'saved' };
            end
        end
    end
    for _, e in ipairs(load_builtin(cz)) do
        if (norm(e.key):find(nq, 1, true)) then
            out[#out + 1] = { n = e.n, key = e.key, x = e.x, y = e.y, z = e.z, src = 'builtin' };
        end
    end
    return out;
end

-- Normalize an angle to [-pi, pi].
local function wrap(a)
    while (a > math.pi) do a = a - 2 * math.pi; end
    while (a < -math.pi) do a = a + 2 * math.pi; end
    return a;
end

-- Relative turn angle (0 = dest ahead, +right) from current heading h and the
-- world delta to the destination, after applying the build-constant flip + offset
-- calibration. Shared by /gps calib and the HUD so they stay consistent.
local function turn_rel(h, dx, dz)
    local base = wrap(math.atan2(dx, dz) - h);
    if (active_flip()) then base = -base; end
    return wrap(base - active_offset());
end

-- The heading to steer by, per the active mode: camera look (camera mode) or the
-- character rotation getter (character mode). Returns nil if unavailable.
local function active_heading(char_h)
    if (cfg.mode == 'camera') then return camera_heading(); end
    return char_h;
end

-- Map a relative angle (0 = ahead, +right) to an 8-way word + screen vector.
local function bearing_word(rel)
    local deg = rel * 180 / math.pi;
    local a = math.abs(deg);
    local word;
    if (a <= 22.5) then word = 'AHEAD';
    elseif (a >= 157.5) then word = 'BEHIND';
    elseif (a < 67.5) then word = (deg > 0) and 'AHEAD-RIGHT' or 'AHEAD-LEFT';
    elseif (a <= 112.5) then word = (deg > 0) and 'RIGHT' or 'LEFT';
    else word = (deg > 0) and 'BEHIND-RIGHT' or 'BEHIND-LEFT';
    end
    return word, deg;
end

-- Optional graphical arrow; fully guarded so a missing draw binding just no-ops.
local function draw_arrow(rel)
    pcall(function()
        local dl = imgui.GetWindowDrawList();
        local ox, oy = imgui.GetCursorScreenPos();
        local r = 26;
        local cx, cy = ox + r, oy + r;
        imgui.Dummy({ r * 2, r * 2 });
        dl:AddCircle({ cx, cy }, r, 0x66FFFFFF, 24, 1.5);
        -- screen: up = -y, clockwise positive (right)
        local s, c = math.sin(rel), math.cos(rel);
        local tipx, tipy = cx + s * r, cy - c * r;            -- arrow tip
        local bx, by     = cx - s * r * 0.5, cy + c * r * 0.5; -- tail
        -- perpendicular for the barbs
        local px, py = c, s;
        local w = 7;
        dl:AddTriangleFilled(
            { tipx, tipy },
            { bx + px * w, by + py * w },
            { bx - px * w, by - py * w },
            0xFF33CCFF);
    end);
end

ashita.events.register('load', 'load_cb', function ()
    pcall(open_store);
    load_saved();
    load_cfg();
    camera_init();
    load_index();
    pcall(function() load_builtin(cur_zone()); end);  -- warm current zone
end);

-- ----------------------------------------------------------------------------
-- Waypoints: /gps waypoint <zone> <x> <y> <z> <label> routes there in this zone,
-- or arms it to route once you zone in. Coordinates are LSB server-space
-- (pos_x/pos_y/pos_z: y = height), which matches this addon's saved-spot convention.
-- ----------------------------------------------------------------------------
local function route_to(w, how)
    dest = { x = w.x, y = w.y, z = w.z, zone = w.zone };
    arrived_at = nil; nav_far = false;
    hud.show = true;
    msg(('%s "%s": %.1f, %.1f'):format(how, w.n, w.x, w.z));
end

local function receive_waypoint(zid, x, y, z, label, src)
    -- dedupe: the same waypoint again refreshes it instead of stacking
    for i, w in ipairs(inbox) do
        if (w.zone == zid and w.x == x and w.z == z and w.n:lower() == label:lower()) then
            table.remove(inbox, i);
            break;
        end
    end
    local w = { n = label, x = x, y = y, z = z, zone = zid, armed = false, t = os.clock(), src = src };
    table.insert(inbox, 1, w);
    while (#inbox > INBOX_CAP) do table.remove(inbox); end

    local cz = cur_zone();
    if (zid == cz) then
        route_to(w, 'routing to');
    else
        -- the latest Go wins: older command arms stand down
        for _, o in ipairs(inbox) do
            if (o ~= w and o.src == 'command') then o.armed = false; end
        end
        w.armed = true;
        msg(('"%s" is in %s; routes when you zone in.'):format(label, zone_name(zid)));
    end
end

ashita.events.register('zone_change', 'zone_cb', function ()
    pcall(function() load_builtin(cur_zone()); end);  -- warm the new zone's data
end);

-- Armed waypoints can't fire from zone_change: that event arrives BEFORE
-- party memory reports the new zone, so cur_zone() still reads the old one.
-- Instead they're polled (throttled) from the d3d_present tick, where the zone
-- read is settled. Fires each waypoint at most once (armed flag cleared).
local last_arm_check = 0;
local function check_armed()
    if (#inbox == 0) then return; end
    local cz = cur_zone();
    if (cz == nil or cz == 0) then return; end
    for _, w in ipairs(inbox) do
        if (w.armed and w.zone == cz) then
            w.armed = false;
            route_to(w, 'routing to');
            return;
        end
    end
end

ashita.events.register('command', 'command_cb', function (e)
    local args = e.command:args();
    if (#args == 0 or not args[1]:any('/gps')) then return; end
    e.blocked = true;

    local sub = (#args >= 2) and args[2]:lower() or nil;

    if (sub == 'print') then
        local x, y, z = get_pos();
        if (x == nil) then
            msg('position unavailable.');
        else
            msg(('X: %.3f  Y: %.3f  Z: %.3f'):format(x, y, z));
        end
        return;
    elseif (sub == 'dest') then
        local x = tonumber(args[3]);
        local z = tonumber(args[4]);
        if (x == nil or z == nil) then
            msg('usage: /gps dest <x> <z>');
            return;
        end
        dest = { x = x, z = z, zone = cur_zone() };
        arrived_at = nil; nav_far = false;
        hud.show = true;
        msg(('destination set: %.3f, %.3f'):format(x, z));
        return;
    elseif (sub == 'here') then
        local x, y, z = get_pos();
        if (x == nil) then
            msg('position unavailable.');
            return;
        end
        dest = { x = x, y = y, z = z, zone = cur_zone() };
        arrived_at = nil; nav_far = false;
        hud.show = true;
        msg(('destination marked here: %.3f, %.3f'):format(x, z));
        return;
    elseif (sub == 'save') then
        local name = join_name(args, 3);
        if (name == nil) then
            msg('usage: /gps save <name>');
            return;
        end
        local x, y, z = get_pos();
        if (x == nil) then
            msg('position unavailable.');
            return;
        end
        local zid = cur_zone();
        if (zid == nil) then
            msg('current zone unknown; cannot save.');
            return;
        end
        saved[zid] = saved[zid] or {};
        saved[zid][name] = { x = x, y = y, z = z };
        save_saved();
        msg(('saved "%s": %.3f, %.3f (%s)'):format(name, x, z, zone_name(zid)));
        return;
    elseif (sub == 'go' or sub == 'load') then
        local name = join_name(args, 3);
        if (name == nil) then
            msg('usage: /gps go <name>  (partial names work)');
            return;
        end
        local c, zid, src = find_spot(name);   -- exact match first
        if (c == nil) then
            -- No exact hit: try partial (substring) matching in the current zone.
            local matches = search_zone(name);
            local distinct = {};               -- key -> display name
            for _, m in ipairs(matches) do distinct[m.key] = m.n; end
            local dnames = {};
            for _, dn in pairs(distinct) do dnames[#dnames + 1] = dn; end
            if (#dnames == 0) then
                msg('no location "' .. tostring(name) .. '". try /gps find <text>');
                return;
            elseif (#dnames > 1) then
                table.sort(dnames, function(a, b) return a:lower() < b:lower(); end);
                msg(('%d matches for "%s" -- type more of the name (or the full name):'):format(#dnames, name));
                for i = 1, math.min(#dnames, 12) do msg('  ' .. dnames[i]); end
                if (#dnames > 12) then msg(('  ... +%d more'):format(#dnames - 12)); end
                return;
            end
            -- Exactly one distinct name: route to the nearest matching instance.
            local px, _, pz = get_pos();
            local best, bestd;
            for _, m in ipairs(matches) do
                if (px == nil) then best = m; break; end
                local dx, dz = px - m.x, pz - m.z;
                local d = dx * dx + dz * dz;
                if (bestd == nil or d < bestd) then bestd = d; best = m; end
            end
            c = { x = best.x, y = best.y, z = best.z };
            zid = cur_zone(); src = best.src; name = best.n;
        end
        dest = { x = c.x, y = c.y, z = c.z, zone = zid };
        arrived_at = nil; nav_far = false;
        hud.show = true;
        local cz = cur_zone();
        local tag = (src == 'builtin') and ' [npc]' or '';
        if (zid ~= nil and cz ~= nil and zid ~= cz) then
            msg(('routing to "%s" -- but it is in %s, not your zone'):format(name, zone_name(zid)));
        else
            msg(('routing to "%s": %.1f, %.1f%s'):format(name, c.x, c.z, tag));
        end
        return;
    elseif (sub == 'find') then
        local q = join_name(args, 3);
        if (q == nil) then
            msg('usage: /gps find <text>');
            return;
        end
        local cz = cur_zone();
        local hits = search_zone(q);
        if (#hits == 0) then
            msg(('no match for "%s" in %s.'):format(q, zone_name(cz)));
            return;
        end
        table.sort(hits, function(a, b) return a.n:lower() < b.n:lower(); end);
        AshitaCore:GetChatManager():AddChatMessage(206, false,
            color(2, ('--- find "%s" in %s (%d) ---'):format(q, zone_name(cz), #hits)));
        for i = 1, math.min(#hits, 30) do
            local h = hits[i];
            msg(('  %s%s: %.1f, %.1f'):format(h.n, (h.src == 'saved') and ' (saved)' or '', h.x, h.z));
        end
        if (#hits > 30) then msg(('  ... +%d more; narrow the search.'):format(#hits - 30)); end
        return;
    elseif (sub == 'list' and args[3]) then
        local filt = args[3]:lower();
        local cz = cur_zone();
        local list = (cz ~= nil) and load_builtin(cz) or {};
        local function collect(k)   -- names whose lowercased k tag == k (k=nil -> all)
            local out = {};
            for _, e in ipairs(list) do
                if (k == nil or (e.k ~= nil and tostring(e.k):lower() == k)) then
                    out[#out + 1] = e.n;
                end
            end
            return out;
        end
        local names;
        if (filt == 'all') then
            names = collect(nil);
        else
            -- literal k match first, so a hand-edited custom tag (e.g. k='TE') is
            -- listable as /gps list te; fall back to a friendly alias only if the
            -- literal tag isn't present (te -> statue, plurals -> singular, ...).
            names = collect(filt);
            local alias = KIND_ALIAS[filt];
            if (#names == 0 and alias ~= nil and alias ~= filt) then
                names = collect(alias);
            end
        end
        if (#names == 0) then
            local tags, seen = {}, {};
            for _, e in ipairs(list) do
                local k = e.k and tostring(e.k):lower();
                if (k ~= nil and not seen[k]) then seen[k] = true; tags[#tags + 1] = k; end
            end
            table.sort(tags);
            msg(('no "%s" in %s.'):format(filt, zone_name(cz)));
            if (#tags > 0) then msg('  tags here: all, ' .. table.concat(tags, ', ')); end
            return;
        end
        table.sort(names, function(a, b) return a:lower() < b:lower(); end);
        AshitaCore:GetChatManager():AddChatMessage(206, false,
            color(2, ('--- %s: %s (%d) ---'):format(zone_name(cz), filt, #names)));
        for _, n in ipairs(names) do msg('  ' .. n); end
        return;
    elseif (sub == 'list') then
        local zids = {};
        for zid, bucket in pairs(saved) do
            if (next(bucket) ~= nil) then zids[#zids + 1] = zid; end
        end
        if (#zids == 0) then
            msg('no saved spots. /gps save <name>');
            return;
        end
        table.sort(zids, function(a, b) return zone_name(a) < zone_name(b); end);
        AshitaCore:GetChatManager():AddChatMessage(206, false, color(2, '--- saved spots ---'));
        for _, zid in ipairs(zids) do
            AshitaCore:GetChatManager():AddChatMessage(206, false, color(68, zone_name(zid)));
            local names = {};
            for n in pairs(saved[zid]) do names[#names + 1] = n; end
            table.sort(names);
            for _, n in ipairs(names) do
                local c = saved[zid][n];
                msg(('  %s: %.1f, %.1f'):format(n, c.x, c.z));
            end
        end
        return;
    elseif (sub == 'del' or sub == 'delete' or sub == 'rm') then
        local name = join_name(args, 3);
        -- Only user-saved spots can be deleted (built-in NPC data is read-only).
        local dzid;
        local cz = cur_zone();
        if (name ~= nil and cz ~= nil and saved[cz] and saved[cz][name]) then
            dzid = cz;
        elseif (name ~= nil) then
            for zid, bucket in pairs(saved) do
                if (bucket[name]) then dzid = zid; break; end
            end
        end
        if (dzid == nil) then
            msg('no saved spot "' .. tostring(name) .. '". /gps list');
            return;
        end
        saved[dzid][name] = nil;
        if (next(saved[dzid]) == nil) then saved[dzid] = nil; end  -- drop empty bucket
        save_saved();
        msg(('deleted "%s" (%s)'):format(name, zone_name(dzid)));
        return;
    elseif (sub == 'waypoint') then
        local zid, x, y, z = tonumber(args[3]), tonumber(args[4]), tonumber(args[5]), tonumber(args[6]);
        local t = {};
        for i = 7, #args do t[#t + 1] = args[i]; end
        local label = table.concat(t, ' '):gsub('^%s+', ''):gsub('%s+$', ''):gsub('^"', ''):gsub('"$', '');
        if (zid == nil or x == nil or y == nil or z == nil or label == '') then
            msg('usage: /gps waypoint <zone> <x> <y> <z> <label>');
            return;
        end
        receive_waypoint(zid, x, y, z, label, 'command');
        return;
    elseif (sub == 'clear') then
        dest = nil;
        msg('destination cleared.');
        return;
    elseif (sub == 'calib') then
        local x, _, z, ch = get_pos();
        local h = active_heading(ch);
        if (x == nil or h == nil) then
            msg((cfg.mode == 'camera') and 'camera heading unavailable; /gps camprobe.' or 'heading unavailable; cannot calibrate.');
            return;
        end
        -- One-time build constant -- no landmark needed. Start watching position;
        -- present_cb finishes once you've run far enough (see CALIB_DIST).
        calib = { x0 = x, z0 = z, t = os.clock() };
        hud.show = true;
        msg(('calibrating [%s]: now RUN FORWARD a few steps (toward where you are looking). Hold a straight line.'):format(cfg.mode));
        return;
    elseif (sub == 'flip') then
        local f = toggle_active_flip();
        save_cfg();
        msg(('turn direction [%s] %s -- re-run /gps calib (run forward) to re-zero.'):format(cfg.mode, f and 'inverted' or 'normal'));
        return;
    elseif (sub == 'vflip') then
        cfg.vert_flip = not cfg.vert_flip;
        save_cfg();
        msg('up/down cue ' .. (cfg.vert_flip and 'inverted' or 'normal'));
        return;
    elseif (sub == 'compact') then
        cfg.compact = not cfg.compact;
        save_cfg();
        msg('compact mode ' .. (cfg.compact and 'on (no title bar)' or 'off'));
        return;
    elseif (sub == 'mode') then
        local m = args[3] and args[3]:lower() or nil;
        if (m == 'camera' or m == 'cam') then m = 'camera'; end
        if (m == 'character' or m == 'char') then m = 'character'; end
        if (m ~= 'camera' and m ~= 'character') then
            msg(('mode is [%s]. usage: /gps mode camera | character'):format(cfg.mode));
            return;
        end
        if (m == 'camera' and camera_heading() == nil) then
            msg('camera heading unavailable on this build -- run /gps camprobe. Staying in character mode.');
            return;
        end
        cfg.mode = m;
        save_cfg();
        msg(('mode -> %s. Run /gps calib then run forward a few steps to zero the arrow.'):format(m));
        return;
    elseif (sub == 'camprobe') then
        if (cam_ptr_addr == 0) then camera_init(); end
        if (cam_ptr_addr == 0) then
            msg('camera signature not found in FFXiMain.dll -- camera mode unavailable.');
            return;
        end
        local cam_x, cam_ns, focal_x, focal_ns = camera_floats();
        if (cam_x == nil) then
            msg('camera pointer resolved but struct read failed (try after fully zoned in).');
            return;
        end
        msg(('cam=(%.2f, %.2f) focal=(%.2f, %.2f)'):format(cam_x, cam_ns, focal_x, focal_ns));
        msg(('camera heading = %.1f deg'):format(camera_heading() * 180 / math.pi));
        return;
    elseif (sub == 'help') then
        show_help();
        return;
    elseif (sub ~= nil) then
        msg('unknown command. /gps help');
        return;
    end

    hud.show = not hud.show;
    msg('HUD ' .. (hud.show and 'on' or 'off'));
end);

ashita.events.register('d3d_present', 'present_cb', function ()
    -- armed waypoints (checked even with the HUD hidden)
    if (os.clock() - last_arm_check >= 2) then
        last_arm_check = os.clock();
        pcall(check_armed);
    end

    if (not hud.show) then return; end

    local x, y, z, h = get_pos();

    -- Walk-calibration in progress: measure real travel direction vs the heading
    -- reading and lock in the offset once you've moved far enough.
    if (calib ~= nil) then
        local sh = active_heading(h);
        if (x ~= nil and sh ~= nil) then
            local mdx, mdz = x - calib.x0, z - calib.z0;
            local moved = math.sqrt(mdx * mdx + mdz * mdz);
            if (moved >= CALIB_DIST) then
                local base = wrap(math.atan2(mdx, mdz) - sh);  -- travel dir vs heading
                if (active_flip()) then base = -base; end
                set_active_offset(base);
                save_cfg();
                calib = nil;
                msg(('calibrated [%s] from your run (offset %.1f deg). If the arrow points OPPOSITE where you ran, /gps flip then /gps calib again.'):format(cfg.mode, base * 180 / math.pi));
            elseif (os.clock() - calib.t > CALIB_TIMEOUT) then
                calib = nil;
                msg('calibration timed out -- /gps calib, then run forward.');
            end
        end
    end

    -- Window sizes itself to whatever lines are actually drawn this frame (idle =
    -- just X/Y/Z; navigating = the whole Dest/Dist/vertical/Turn/arrow block).
    -- GOTCHA: pass a real value (true) for p_open -- Ashita's Begin binding resolves
    -- its overload from the argument list, and a nil there drops the flags argument
    -- entirely, which is why AlwaysAutoResize silently did nothing before v1.21.
    -- Do NOT reintroduce SetNextWindowSize here: it OVERRIDES AlwaysAutoResize.
    -- Size CONSTRAINTS are applied after the auto-fit, so a minimum width is safe
    -- (same pattern the chains addon uses) and keeps the idle box from going narrow.
    local flags = bit.bor(ImGuiWindowFlags_NoNav, ImGuiWindowFlags_AlwaysAutoResize);
    if (cfg.compact) then
        flags = bit.bor(flags, ImGuiWindowFlags_NoDecoration);
    end
    imgui.SetNextWindowBgAlpha(0.55);
    imgui.SetNextWindowSizeConstraints({ 170, -1 }, { FLT_MAX, FLT_MAX });
    if (imgui.Begin('GPS', true, flags)) then
        if (x == nil) then
            imgui.TextColored({ 1.0, 0.5, 0.5, 1.0 }, 'position unavailable');
        else
            -- Numbers are padded to a fixed column width so the auto-sized window
            -- only changes size when a whole SECTION appears/disappears -- not every
            -- frame as the digit count changes while you run (9.500 -> -104.250).
            imgui.Text(('X: %9.3f'):format(x));
            imgui.Text(('Y: %9.3f'):format(y));
            imgui.Text(('Z: %9.3f'):format(z));

            if (calib ~= nil) then
                imgui.Separator();
                imgui.TextColored({ 1.0, 0.85, 0.4, 1.0 }, 'CALIBRATING: run forward...');
            end

            if (dest ~= nil) then
                imgui.Separator();
                imgui.TextColored({ 0.7, 0.9, 1.0, 1.0 }, ('Dest: %8.1f,%8.1f'):format(dest.x, dest.z));

                if (dest.zone ~= nil and cur_zone() ~= nil and dest.zone ~= cur_zone()) then
                    imgui.TextColored({ 1.0, 0.6, 0.3, 1.0 }, 'destination is in another zone');
                else
                    local dx, dz = dest.x - x, dest.z - z;
                    local dist = math.sqrt(dx * dx + dz * dz);
                    imgui.Text(('Dist: %8.1f'):format(dist));

                    if (dist >= ARRIVE_DIST) then nav_far = true; end

                    -- Vertical cue: is the destination above or below me? On this
                    -- build SMALLER height y = higher up (verified in-game), so the
                    -- "up amount" is my y minus the destination's. vflip overrides.
                    if (dest.y ~= nil and y ~= nil) then
                        local up = y - dest.y;
                        if (cfg.vert_flip) then up = -up; end
                        if (up > VERT_DEADBAND) then
                            imgui.TextColored({ 0.5, 0.8, 1.0, 1.0 }, ('Up   %4.0fy  ^'):format(up));
                        elseif (up < -VERT_DEADBAND) then
                            imgui.TextColored({ 1.0, 0.8, 0.4, 1.0 }, ('Down %4.0fy  v'):format(-up));
                        else
                            imgui.TextColored({ 0.7, 0.7, 0.7, 1.0 }, 'Level');
                        end
                    end

                    local sh = active_heading(h);  -- camera or character heading
                    if (dist < ARRIVE_DIST) then
                        -- Stamp arrival the first frame we land (only if we actually
                        -- travelled here), flash ARRIVED, then auto-clear the dest.
                        if (nav_far and arrived_at == nil) then arrived_at = os.clock(); end
                        local blink = (arrived_at == nil)
                            or (math.floor((os.clock() - arrived_at) * 4) % 2 == 0);
                        if (blink) then
                            imgui.TextColored({ 0.3, 1.0, 0.4, 1.0 }, 'ARRIVED');
                        else
                            imgui.Text(' ');  -- keep the line height during the blink-off
                        end
                        if (arrived_at ~= nil and (os.clock() - arrived_at) > ARRIVE_FLASH_S) then
                            dest = nil; arrived_at = nil; nav_far = false;
                        end
                    elseif (sh == nil) then
                        imgui.TextColored({ 1.0, 0.6, 0.3, 1.0 },
                            (cfg.mode == 'camera') and '(no camera - /gps camprobe)' or '(no heading - turn unavailable)');
                    else
                        local rel = turn_rel(sh, dx, dz);
                        local word, deg = bearing_word(rel);
                        -- %-12s fits the longest bearing word (BEHIND-RIGHT) so the
                        -- line holds one width as the arrow swings around.
                        imgui.Text(('Turn: %-12s %3d deg  [%s]'):format(word, math.floor(math.abs(deg) + 0.5), cfg.mode));
                        if (active_offset() == 0 and not active_flip()) then
                            imgui.TextColored({ 1.0, 0.85, 0.4, 1.0 }, 'uncalibrated: /gps calib');
                        end
                        draw_arrow(rel);
                    end
                end
            end
        end
    end
    imgui.End();
end);
