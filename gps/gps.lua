-- Walk-calibration: while active we watch your position; once you've moved
-- CALIB_DIST yalms we compare your real travel direction to the heading reading
-- and store the offset. No landmark needed -- you just run forward.
local calib = nil;            -- { x0, z0, t } while a calibration run is in progress
local CALIB_DIST    = 4.0;    -- yalms of straight running needed to lock it in
local CALIB_TIMEOUT = 20.0;   -- seconds before an unfinished calibration gives up

-- Camera heading for the camera-relative arrow (mode = 'camera'). Read straight
-- from FFXiMain.dll via the same XICamera pointer chain fancycompass uses (a plain
-- memory READ -- no packets). CEXI runs the retail client so the signature matches.
--   sig +0x10            -> address of the global holding the camera struct pointer
--   base +0x44 / +0x50   -> X (east-west) camera / focal
--   base +0x4C / +0x58   -> north-south (the horizontal forward/back axis)
-- heading = atan2(Xdelta, NSdelta), which is already our bearing convention
-- (atan2(dx, dz)); any residual offset/sign is absorbed by calib + flip.
local CAM_SIG = '83C40485C974118B116A01FF5218C705';
local cam_ptr_addr = 0;

local function camera_init()
    local ok = pcall(function()
        local sig = ashita.memory.find('FFXiMain.dll', 0, CAM_SIG, 0, 0);
        if (sig ~= 0) then cam_ptr_addr = ashita.memory.read_uint32(sig + 0x10); end
    end);
    if (not ok) then cam_ptr_addr = 0; end
end

-- Build-constant heading calibration (see header), kept PER MODE because the
-- character-rotation getter and the camera each need their own offset/flip:
--   mode      : 'character' (heading from the rotation getter) or 'camera'
--               (heading from the FFXiMain camera struct -- relative to where
--               you're looking, which feels more natural for steering).
--   *_offset  : zeroes the fixed gap between that heading source and true bearing.
--   *_flip    : inverts the rotation sense for that source.
-- Persisted in gps_cfg.lua so it survives reloads.
--   vert_flip : inverts the up/down cue if larger height reads as the wrong way on
--               this build (height sign is unverified; /gps vflip corrects it).
--   compact   : drop the title bar/border for a minimal HUD (still draggable by
--               its body; /gps compact).
local cfg = {
    mode        = 'camera',   -- default; the user's choice persists in gps_cfg.lua
    char_offset = 0.0, char_flip = false,
    cam_offset  = 0.0, cam_flip  = false,
    vert_flip   = false,
    compact     = false,
};
-- Saves live in config\addons\gps\, outside the addon folder the launcher replaces.
local store_dir = ('%sconfig\\addons\\gps\\'):format(AshitaCore:GetInstallPath());
local cfg_path = store_dir .. 'gps_cfg.lua';

-- A save 1.22 or older left in the addon folder is copied once, never deleted.
local function adopt(name)
    local have = io.open(store_dir .. name, 'rb');
    if (have ~= nil) then have:close(); return; end
    local old = io.open(addon.path .. name, 'rb');
    if (old == nil) then return; end
    local body = old:read('*a');
    old:close();
    local new = io.open(store_dir .. name, 'wb');
    if (new == nil) then return; end
    new:write(body);
    new:close();
end

local function open_store()
    if (not ashita.fs.exists(store_dir)) then ashita.fs.create_directory(store_dir); end
    adopt('gps_cfg.lua');
    adopt('saved_gps.lua');
end

local function save_cfg()
    local f = io.open(cfg_path, 'w');
    if (f == nil) then return; end
    f:write(('return {\n  mode = %q,\n  char_offset = %s, char_flip = %s,\n  cam_offset = %s, cam_flip = %s,\n  vert_flip = %s,\n  compact = %s,\n}\n'):format(
        cfg.mode,
        tostring(cfg.char_offset), tostring(cfg.char_flip),
        tostring(cfg.cam_offset), tostring(cfg.cam_flip),
        tostring(cfg.vert_flip), tostring(cfg.compact)));
    f:close();
end

local function load_cfg()
    local fn = loadfile(cfg_path);
    if (not fn) then return; end
    local ok, r = pcall(fn);
    if (not ok or type(r) ~= 'table') then return; end
    if (r.mode == 'character' or r.mode == 'camera') then cfg.mode = r.mode; end
    if (type(r.char_offset) == 'number') then cfg.char_offset = r.char_offset; end
    if (type(r.char_flip) == 'boolean') then cfg.char_flip = r.char_flip; end
    if (type(r.cam_offset) == 'number') then cfg.cam_offset = r.cam_offset; end
    if (type(r.cam_flip) == 'boolean') then cfg.cam_flip = r.cam_flip; end
    if (type(r.vert_flip) == 'boolean') then cfg.vert_flip = r.vert_flip; end
    if (type(r.compact) == 'boolean') then cfg.compact = r.compact; end
    -- Migrate the v1.6 flat shape (heading_offset/flip) into the character slot.
    if (type(r.heading_offset) == 'number') then cfg.char_offset = r.heading_offset; end
    if (type(r.flip) == 'boolean') then cfg.char_flip = r.flip; end
end

-- Active mode's calibration (so calib/flip/turn-math all read one source).
local function active_offset() return (cfg.mode == 'camera') and cfg.cam_offset or cfg.char_offset; end
local function active_flip()   return (cfg.mode == 'camera') and cfg.cam_flip   or cfg.char_flip;   end
local function set_active_offset(v)
    if (cfg.mode == 'camera') then cfg.cam_offset = v; else cfg.char_offset = v; end
end
local function toggle_active_flip()
    if (cfg.mode == 'camera') then cfg.cam_flip = not cfg.cam_flip; return cfg.cam_flip;
    else cfg.char_flip = not cfg.char_flip; return cfg.char_flip; end
end

-- Raw camera struct floats (cam_x, cam_ns, focal_x, focal_ns) or nil. Re-resolves
-- the pointer lazily if it wasn't found at load (e.g. addon loaded pre-zone-in).
local function camera_floats()
    if (cam_ptr_addr == 0) then camera_init(); end
    if (cam_ptr_addr == 0) then return nil; end
    local out;
    local ok = pcall(function()
        local base = ashita.memory.read_uint32(cam_ptr_addr);
        if (base == 0) then return; end
        local cam_x    = ashita.memory.read_float(base + 0x44);
        local cam_ns   = ashita.memory.read_float(base + 0x4C);
        local focal_x  = ashita.memory.read_float(base + 0x50);
        local focal_ns = ashita.memory.read_float(base + 0x58);
        -- NaN check (x ~= x) + sane range, mirroring fancycompass.
        if (cam_x == cam_x and focal_x == focal_x and cam_x > -10000 and cam_x < 10000) then
            out = { cam_x, cam_ns, focal_x, focal_ns };
        end
    end);
    if (ok and out ~= nil) then return out[1], out[2], out[3], out[4]; end
    return nil;
end

-- Camera heading in our bearing convention (atan2(dx, dz)). nil if unreadable.
local function camera_heading()
    local cam_x, cam_ns, focal_x, focal_ns = camera_floats();
    if (cam_x == nil) then return nil; end
    return math.atan2(cam_x - focal_x, cam_ns - focal_ns);
end

