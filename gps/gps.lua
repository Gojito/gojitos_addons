--[[
* gps - show your own world X / Y / Z position, plus a simple GPS:
* set a destination coord in the current zone and get live distance + a
* turn arrow relative to the way you're facing.
*
* Ashita 4 / CatsEyeXI. Axis quirk on this client:
*   GetLocalPositionX -> world X
*   GetLocalPositionY -> world Z (horizontal forward/back)
*   GetLocalPositionZ -> world Y (vertical height)
* We swap Y/Z below to present {x, y, z} the way zone spawn-point tables do
* (y = height). Heading convention: facing direction = atan2(dx, dz),
* i.e. forward = (sin H, cos H) in (x,z).
*
* Commands:
*   /gps                toggle the HUD
*   /gps print          echo current position to chat once
*   /gps dest <x> <z>   set GPS destination in this zone
*   /gps here           set destination to where you stand now
*   /gps save <name>    save your current spot
*   /gps go <name>      route to a saved spot OR built-in NPC/location; accepts a
*                          PARTIAL name -- routes if unique, else asks you to refine
*   /gps find <text>    search this zone (saved + built-in) for a name
*   /gps list           list your saved spots
*   /gps list <type>    list built-ins by type (all, npc, nm, coffer,
*                          chest, statue, door)
*   /gps del <name>     delete a saved spot
*   /gps clear          clear the destination
*   /gps compact        toggle the minimal (no title bar) HUD look
*   /gps mode camera|character   steer by camera look vs character facing
*   /gps calib          one-time: run this, then RUN FORWARD a few steps
*   /gps flip           invert left/right if the arrow reads backwards
*   /gps vflip          invert the up/down cue if it reads backwards
*   /gps camprobe       diagnose the camera read
*
* Built-in location database: data/<Zone>.lua (generated by tools/gen_pois.py from
* the CatsEyeXI server npc_list) makes every static NPC + named door routable by
* name out of the box, so /gps go gilgamesh works without saving it first.
* data/index.lua maps the runtime zone id to the (zone-named) data file; the current
* zone's file is loaded lazily. User-saved spots always win over built-in entries and
* are never overwritten. When several built-in entries share a name, go picks the
* nearest. The HUD also shows an Up/Down/Level cue from the destination's height vs
* yours (/gps vflip if the height sign reads backwards on this build).
*
* Heading calibration: neither heading source shares the bearing convention out of
* the box. The character rotation getter and the camera heading (from the FFXiMain
* camera struct) both end up off by a fixed angle. This is a ONE-TIME build constant, so
* calibration must NOT depend on knowing where a destination is (that's what the
* arrow is for). Instead /gps calib measures the offset from your own movement:
* it watches your position and, once you've run a few yalms, compares your real
* travel direction to the heading reading. /gps flip handles an inverted rotation
* sense. Kept PER MODE (character vs camera) since the two sources need different
* offsets. All persisted in config\addons\gps\gps_cfg.lua.
*
* Camera mode reads the camera heading straight from FFXiMain.dll via the XICamera
* pointer chain (same method as the fancycompass addon -- a plain memory read), and
* feeds it through the same calib/flip path. If the camera can't be read it falls
* back to character mode; /gps camprobe reports what's available.
--]]

